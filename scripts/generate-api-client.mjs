import { mkdir, readFile, writeFile } from "node:fs/promises";
import { dirname, resolve } from "node:path";
import { fileURLToPath } from "node:url";
import openapiTS, { astToString } from "openapi-typescript";

const root = resolve(dirname(fileURLToPath(import.meta.url)), "..");
const defaultSchema = resolve(root, "packages/domain/openapi.json");
const output = resolve(root, "packages/domain/api.generated.ts");
const source = process.env.OPENAPI_URL || defaultSchema;
const sourceLabel = process.env.OPENAPI_URL || "packages/domain/openapi.json";

const schema = source.startsWith("http://") || source.startsWith("https://")
  ? source
  : JSON.parse(await readFile(resolve(source), "utf8"));

const ast = await openapiTS(schema, { alphabetize: true });
const generated = astToString(ast);
const header = `/**\n * Generated by scripts/generate-api-client.mjs.\n * Source: ${sourceLabel}\n * Do not edit manually; update the OpenAPI contract and regenerate.\n */\n\n`;

await mkdir(dirname(output), { recursive: true });
await writeFile(output, `${header}${generated}`, "utf8");
console.log(`Generated ${output} from ${source}`);
